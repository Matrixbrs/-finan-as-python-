from bcb import sgs
import pandas as pd
import matplotlib.pyplot as plt

def get_accumulated_cdi(start_date: str, end_date: str) -> pd.DataFrame:
    """
    Fetches daily CDI rates from BCB API and calculates cumulative return.
    Dates must be in YYYY-MM-DD format.
    """
    #  CDI rates (Series 12)
    df = sgs.get({'cdi': 12}, start=start_date, end=end_date)

    # Convert percentages to absolute decimals (e.g., 0.05% -> 0.0005)
    df['daily_decimal'] = df['cdi'] / 100

    # Calculate geometric accumulation: Product of (1 + daily_rate)
    df['cdi_benchmark'] = (1 + df['daily_decimal']).cumprod() - 1

    # Convert benchmark back to a readable percentage format
    df['cdi_benchmark_pct'] = df['cdi_benchmark'] * 100

    return df[['cdi', 'cdi_benchmark_pct']]

