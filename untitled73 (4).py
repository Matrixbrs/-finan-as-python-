def black_scholes_vega(S, K, T, r, sigma):
    """
    Calcula o Vega de uma opção usando o modelo Black-Scholes.
    """
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    vega = S * norm.pdf(d1) * np.sqrt(T)
    return vega

