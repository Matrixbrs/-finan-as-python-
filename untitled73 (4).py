def black_scholes_gamma(S, K, T, r, sigma):
    """
    Calcula o Gamma de uma opção usando o modelo Black-Scholes.
    """
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    gamma = norm.pdf(d1) / (S * sigma * np.sqrt(T))
    return gamma

