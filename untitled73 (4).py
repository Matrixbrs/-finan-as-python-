def black_scholes_call(S, K, T, r, sigma):
    """
    Calcula o preço de uma opção de compra (Call) usando o modelo Black-Scholes.

    Parâmetros:
    S (float): Preço atual do ativo subjacente
    K (float): Preço de exercício da opção
    T (float): Tempo até a expiração (em anos)
    r (float): Taxa de juros livre de risco anual (em decimal)
    sigma (float): Volatilidade anual do ativo subjacente (em decimal)

    Retorna:
    float: Preço da opção de compra
    """
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    call_price = S * norm.cdf(d1) - K * np.exp(-r * T) * norm.cdf(d2)
    return call_price

def black_scholes_put(S, K, T, r, sigma):
    """
    Calcula o preço de uma opção de venda (Put) usando o modelo Black-Scholes.

    Parâmetros:
    S (float): Preço atual do ativo subjacente
    K (float): Preço de exercício da opção
    T (float): Tempo até a expiração (em anos)
    r (float): Taxa de juros livre de risco anual (em decimal)
    sigma (float): Volatilidade anual do ativo subjacente (em decimal)

    Retorna:
    float: Preço da opção de venda
    """
    d1 = (np.log(S / K) + (r + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)

    put_price = K * np.exp(-r * T) * norm.cdf(-d2) - S * norm.cdf(-d1)
    return put_price

