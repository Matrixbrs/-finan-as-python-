"""### indice de Sharpe d cada ativo
 métricas:

 **Retorno Médio Diário**: A média dos retornos diários de cada ativo.
  **Desvio Padrão Diário (Volatilidade)**: O desvio padrão dos retornos diários de cada ativo.
  **Taxa Livre de Risco**: Para simplificar, usaremos 0% para o cálculo diário, mas em um cenário real, você usaria a taxa de um ativo sem risco (como títulos do tesouro). Uma taxa anualizada pode ser convertida para diária. Para o Sharpe Ratio anualizado, multiplicaremos o Sharpe Ratio diário pela raiz quadrada do número de dias de negociação em um ano (geralmente 252).
"""

# Calculate daily average returns
daily_avg_returns = returns_aligned.mean()

# Calculate daily standard deviation (volatility)
daily_std_dev = returns_aligned.std()

# Assuming a risk-free rate of 2% per year
annual_risk_free_rate = 0.02
# Convert annual risk-free rate to daily rate (assuming 252 trading days)
risk_free_rate_daily = (1 + annual_risk_free_rate)**(1/252) - 1

# Calculate daily Sharpe Ratio
daily_sharpe_ratio = (daily_avg_returns - risk_free_rate_daily) / daily_std_dev

# Annualize Sharpe Ratio (assuming 252 trading days in a year)
annualized_sharpe_ratio = daily_sharpe_ratio * np.sqrt(252)

# Create a DataFrame to display the risk metrics
risk_metrics = pd.DataFrame({
    'Daily Average Return': daily_avg_returns,
    'Daily Volatility (Std Dev)': daily_std_dev,
    'Daily Sharpe Ratio': daily_sharpe_ratio,
    'Annualized Sharpe Ratio': annualized_sharpe_ratio
})

print("Métricas de Risco por Ativo (com taxa livre de risco de 2% ao ano):")
