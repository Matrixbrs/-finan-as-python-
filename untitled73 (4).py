    regime_prob_df.loc[smoothed_p.index, asset] = smoothed_p.values
    high_idx = smoothed_p[smoothed_p > 0.5].index #separate observations by regime
    low_idx = smoothed_p[smoothed_p <= 0.5].index
    high_r = r.loc[high_idx]
